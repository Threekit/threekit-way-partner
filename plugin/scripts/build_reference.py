#!/usr/bin/env python3
"""Generate skills/goto-platform/references/api-reference.md from an OpenAPI snapshot of the live platform.

Usage: python3 scripts/build_reference.py refresh/snapshots/<date>/openapi.json [--out <path>] [--date YYYY-MM-DD]

The reference is never written by hand. The platform-refresh agent fetches today's spec from
https://app.threekit.ai/docs/openapi.json, saves it under refresh/snapshots/<date>/, runs this
script, and the change agent approves the diff. Everything in the output comes from the spec:
the platform's own notes, every operation grouped by tag, its parameters, request body and
response schema, and every schema's fields. Standard library only.
"""
import sys
import os
import json
import datetime as dt

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_OUT = os.path.join(ROOT, "skills", "goto-platform", "references", "api-reference.md")
VERBS = ("get", "post", "put", "patch", "delete")


def opt(flag, default=None):
    if flag in sys.argv:
        return sys.argv[sys.argv.index(flag) + 1]
    return default


def deref(spec, node, depth=0):
    """Follow $ref once so we can read properties; keep the name for display."""
    if isinstance(node, dict) and "$ref" in node:
        name = node["$ref"].split("/")[-1]
        target = spec.get("components", {}).get("schemas", {}).get(name)
        return name, (target or {})
    return None, (node or {})


def typ(spec, node):
    if not isinstance(node, dict):
        return "?"
    if "$ref" in node:
        return node["$ref"].split("/")[-1]
    for k in ("anyOf", "oneOf", "allOf"):
        if k in node:
            parts = [typ(spec, n) for n in node[k]]
            parts = [p for p in parts if p and p != "null"]
            return " or ".join(dict.fromkeys(parts)) or "any"
    t = node.get("type")
    if t == "array":
        return "list of " + typ(spec, node.get("items", {}))
    if "enum" in node:
        return "one of " + ", ".join(str(e) for e in node["enum"][:12]) + (" ..." if len(node["enum"]) > 12 else "")
    if t == "object" and node.get("properties"):
        return "object"
    return t or "any"


def fields(spec, node, indent="", depth=0, seen=None):
    """One line per field: name, type, required, description. Inline nested objects two levels down."""
    seen = seen or set()
    name, s = deref(spec, node)
    if name and name in seen:
        return [f"{indent}- (see {name})"]
    if name:
        seen = seen | {name}
    out = []
    if "allOf" in s:
        for part in s["allOf"]:
            out += fields(spec, part, indent, depth, seen)
        return out
    props = s.get("properties") or {}
    req = set(s.get("required") or [])
    for k, v in props.items():
        desc = (v.get("description") or "").strip().replace("\n", " ")
        line = f"{indent}- `{k}` {typ(spec, v)}{' (required)' if k in req else ''}"
        if desc:
            line += ": " + (desc[:220] + ("..." if len(desc) > 220 else ""))
        out.append(line)
        inner_name, inner = deref(spec, v)
        if depth < 2 and (inner.get("properties") or (v.get("type") == "array" and deref(spec, v.get("items", {}))[1].get("properties"))):
            target = v if inner.get("properties") else v.get("items", {})
            out += fields(spec, target, indent + "  ", depth + 1, seen)
    if not props and s.get("enum"):
        out.append(f"{indent}- one of: " + ", ".join(str(e) for e in s["enum"]))
    return out


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(2)
    path = sys.argv[1]
    out_path = opt("--out", DEFAULT_OUT)
    date = opt("--date", dt.date.today().isoformat())
    with open(path, "r", encoding="utf-8") as f:
        spec = json.load(f)
    info = spec.get("info", {})
    paths = spec.get("paths", {})
    ops = []
    for p, methods in paths.items():
        for verb, op in methods.items():
            if verb not in VERBS or not isinstance(op, dict):
                continue
            ops.append((p, verb.upper(), op))
    tags = {}
    for p, verb, op in ops:
        for t in op.get("tags") or ["untagged"]:
            tags.setdefault(t, []).append((p, verb, op))
    tag_desc = {t["name"]: t.get("description", "") for t in spec.get("tags", [])}
    sec = spec.get("components", {}).get("securitySchemes", {})

    L = []
    L.append(f"# {info.get('title', 'Threekit Platform API')} reference, generated")
    L.append("")
    L.append(f"Generated by scripts/build_reference.py from the live OpenAPI spec on {date}. API version "
             f"{info.get('version', '?')}, {len(ops)} operations in {len(tags)} groups. Do not edit by hand: the "
             "platform-refresh agent regenerates this file and the change agent approves the diff. The live "
             "platform wins over this file; run the goto-platform discovery step first.")
    L.append("")
    L.append("Source: https://app.threekit.ai/docs/openapi.json (public).")
    L.append("")
    if sec:
        L.append("## Authentication")
        L.append("")
        for name, s in sec.items():
            L.append(f"- `{name}`: {s.get('type', '')} {s.get('scheme', '')} {('in ' + s.get('in', '')) if s.get('in') else ''} "
                     f"{('header ' + s.get('name', '')) if s.get('name') else ''} {(' ' + s.get('description', '')).strip()}".strip())
        L.append("")
    if info.get("description"):
        L.append("## The platform's own notes")
        L.append("")
        L.append(info["description"].strip())
        L.append("")
    L.append("## Groups of operations")
    L.append("")
    for t in sorted(tags):
        L.append(f"- {t}: {len(tags[t])} operation{'s' if len(tags[t]) != 1 else ''}" + (f". {tag_desc[t].strip()}" if tag_desc.get(t) else ""))
    L.append("")
    for t in sorted(tags):
        L.append(f"## {t}")
        L.append("")
        if tag_desc.get(t):
            L.append(tag_desc[t].strip())
            L.append("")
        L.append("| Method | Path | What it does |")
        L.append("|---|---|---|")
        for p, verb, op in sorted(tags[t], key=lambda x: (x[0], x[1])):
            summ = (op.get("summary") or op.get("operationId") or "").strip().replace("|", "/")
            L.append(f"| {verb} | `{p}` | {summ} |")
        L.append("")
        for p, verb, op in sorted(tags[t], key=lambda x: (x[0], x[1])):
            L.append(f"### {verb} `{p}`")
            L.append("")
            if op.get("description"):
                L.append(op["description"].strip()[:1200])
                L.append("")
            params = op.get("parameters") or []
            if params:
                L.append("Parameters:")
                for q in params:
                    desc = (q.get("description") or "").strip().replace("\n", " ")
                    L.append(f"- `{q.get('name')}` ({q.get('in')}{', required' if q.get('required') else ''}) {typ(spec, q.get('schema', {}))}"
                             + (f": {desc[:160]}" if desc else ""))
                L.append("")
            rb = (op.get("requestBody") or {}).get("content", {}).get("application/json", {}).get("schema")
            if rb:
                name, _ = deref(spec, rb)
                L.append("Request body" + (f" (`{name}`)" if name else "") + ":")
                L += fields(spec, rb) or ["- (no fields listed)"]
                L.append("")
            for code in ("200", "201"):
                r = (op.get("responses") or {}).get(code, {}).get("content", {}).get("application/json", {}).get("schema")
                if r:
                    name, _ = deref(spec, r)
                    L.append(f"Response {code}" + (f" (`{typ(spec, r)}`)" if name or r.get('type') else "") + ":")
                    L += fields(spec, r if not (r.get("type") == "array") else r.get("items", {})) or ["- (see schema)"]
                    L.append("")
                    break
    schemas = spec.get("components", {}).get("schemas", {})
    if schemas:
        L.append("## Schemas")
        L.append("")
        for name in sorted(schemas):
            L.append(f"### {name}")
            L.append("")
            if schemas[name].get("description"):
                L.append(schemas[name]["description"].strip()[:400])
                L.append("")
            L += fields(spec, {"$ref": "#/components/schemas/" + name}) or ["- (no fields listed)"]
            L.append("")
    text = "\n".join(L).rstrip() + "\n"
    text = text.replace("\u2014", " - ").replace("\u2013", " - ").replace("  - ", " - ")  # spaced hyphen, never an em dash
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"ok: {len(ops)} operations, {len(tags)} groups, {len(schemas)} schemas, written to {out_path}")


if __name__ == "__main__":
    main()
